#!/usr/bin/env python3
"""Generate limits.h from params/scell_params.py so firmware trips can never drift from the design file."""
import sys, pathlib
LAB = pathlib.Path(__file__).resolve().parents[3]; sys.path.insert(0, str(LAB))
from params.scell_params import OPERATE, CELL
o = OPERATE; area = CELL["active_area_cm2"]
L = ["/* GENERATED by gen_limits.py from params/scell_params.py - do not edit by hand */", "#ifndef SCM_LIMITS_H", "#define SCM_LIMITS_H",
     f"#define SCM_N_CELLS            {o['cell_series_max']}",
     f"#define SCM_V_CHARGE_MAX_MV    {int(o['V_charge_max']*1000)}", f"#define SCM_V_DISCHARGE_MIN_MV {int(o['V_discharge_min']*1000)}",
     f"#define SCM_V_TRIP_HIGH_MV     {int(o['V_trip_high']*1000)}", f"#define SCM_V_TRIP_LOW_MV      {int(o['V_trip_low']*1000)}",
     f"#define SCM_T_SET_DC           {int(o['T_set_C']*10)}      /* deci-degC */",
     f"#define SCM_T_MIN_DC           {int(o['T_range_C'][0]*10)}", f"#define SCM_T_MAX_DC           {int(o['T_range_C'][1]*10)}",
     f"#define SCM_T_WARN_DC          {int(o['T_warn_C']*10)}", f"#define SCM_T_TRIP_DC          {int(o['T_trip_C']*10)}",
     f"#define SCM_RAMP_DC_PER_MIN    {int(o['T_ramp_C_per_min']*10)}",
     f"#define SCM_I_MAX_MA           {int(round(o['I_max_mA_cm2']*area))}   /* {o['I_max_mA_cm2']} mA/cm2 x {area:.2f} cm2 */",
     "#endif", ""]
(pathlib.Path(__file__).parent / "limits.h").write_text("\n".join(L))
print("limits.h written")
