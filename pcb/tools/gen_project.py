"""Generate KiCad project + schematic + DRC rules for a board design module.

usage: python gen_project.py <board_dir> <design_module_name>
Writes <board_dir>/<NAME>.kicad_pro/.kicad_sch(+sub-sheets)/.kicad_dru/sym-lib-table/fp-lib-table.
"""
import importlib, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kigen as K  # noqa: E402


def rules_text(mod):
    """Isolation-domain clearance rules (KiCad custom DRC rules)."""
    gap = mod.DOMAIN_GAP
    doms = sorted(mod.regions().keys())
    cls = {dm: mod.netclass_of_domain(dm) for dm in doms}
    lv = mod.LV_CLASSES
    out = ["(version 1)", ""]
    out.append("# --- generated by pcb/tools/gen_project.py: galvanic-isolation domain spacing (see pcb_assumptions.md)")
    for dm in doms:          # island-to-anything spacing (lowest priority)
        if K_kind(mod, dm) == "HV":
            c = cls[dm]
            out.append('(rule "island_%s" (constraint clearance (min %.2fmm)) '
                       '(condition "A.NetClass == \'%s\' && B.NetClass != \'%s\'"))' % (dm, gap[("HV", "HV")], c, c))
    for dm in doms:          # isolated comms vs logic
        if K_kind(mod, dm) == "ISO":
            c = cls[dm]
            cond = " || ".join("B.NetClass == '%s'" % x for x in lv + [cls[o] for o in doms if K_kind(mod, o) == "ISO" and o != dm])
            out.append('(rule "iso_%s" (constraint clearance (min %.2fmm)) (condition "A.NetClass == \'%s\' && (%s)"))'
                       % (dm, gap[("ISO", "LV")], c, cond))
    for dm in doms:          # HV vs logic / comms (highest priority, last)
        if K_kind(mod, dm) == "HV":
            c = cls[dm]
            cond = " || ".join("B.NetClass == '%s'" % x for x in lv + [cls[o] for o in doms if K_kind(mod, o) == "ISO"])
            out.append('(rule "hv_%s" (constraint clearance (min %.2fmm)) (condition "A.NetClass == \'%s\' && (%s)"))'
                       % (dm, gap[("HV", "LV")], c, cond))
    return "\n".join(out) + "\n"


def K_kind(mod, dm):
    return mod.domain_kind(dm)


def main(board_dir, modname):
    sys.path.insert(0, board_dir)
    mod = importlib.import_module(modname)
    d = mod.build()
    K.write_schematic(d, board_dir)
    extra = {}
    if os.path.exists(getattr(mod, "CUSTOM_LIB", "")):
        extra[getattr(mod, "CUSTOM_LIB_NAME", "salt_pcb")] = mod.CUSTOM_LIB
    K.write_lib_tables(d, board_dir, extra)
    nc = mod.netclasses()
    K.write_project(d, board_dir, nc, mod.netclass_patterns(d))
    with open(os.path.join(board_dir, d.name + ".kicad_dru"), "w") as f:
        f.write(rules_text(mod))
    print("generated", d.name, len(d.parts), "parts")


if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]), sys.argv[2])
