def verify():
    soffice = os.environ.get("SOFFICE") or shutil.which("soffice")
    if not soffice or not os.path.exists(soffice):
        return dict(verified=False, reason="LibreOffice not found")
    tmp = Path(tempfile.mkdtemp(prefix="saltxlsx_", dir="/tmp" if os.path.isdir("/tmp") else None))
    prof = f"-env:UserInstallation=file://{tmp}/lo"
    subprocess.run([soffice, prof, "--headless", "--calc", "--convert-to", "xlsx", "--outdir", str(tmp / "x"), str(XLSX)], capture_output=True, timeout=180)
    subprocess.run([soffice, prof, "--headless", "--convert-to", 'csv:Text - txt - csv (StarCalc):44,34,UTF8,1,,0,false,true,false,false,false,-1',
                    "--outdir", str(tmp / "c"), str(XLSX)], capture_output=True, timeout=180)
    errs = []
    for f in glob.glob(str(tmp / "c" / "*.csv")):
        for ln, line in enumerate(open(f, encoding="utf-8", errors="ignore"), 1):
            if re.search(r"#VALUE!|#REF!|#DIV/0!|#NAME\?|#N/A|Err:\d+", line): errs.append(f"{Path(f).name}:{ln}: {line.strip()[:120]}")
    vals = {}
    rx = list((tmp / "x").glob("*.xlsx"))
    if rx:
        from openpyxl import load_workbook
        wb = load_workbook(rx[0], data_only=True)
        def find(sheet, label, col):
            ws = wb[sheet]
            for r in ws.iter_rows(min_row=1, max_row=ws.max_row):
                for c in r:
                    if c.value == label: return ws.cell(c.row, col).value
        vals = dict(cell_materials_usd=find("Cell_BOM", "Cell materials total", 5), cell_usd_kwh=find("Cell_BOM", "Cell materials USD/kWh", 5),
                    beta_share=find("Cell_BOM", "beta''-alumina share of materials", 5), module_usd=find("Module_BOM", "Module materials + bought-in parts (USD)", 7),
                    module_usd_kwh=find("Module_BOM", "Module USD/kWh (materials, no conversion)", 7), x_over_target=find("Module_BOM", "x over founder USD 3/kWh target", 7),
                    standby_W=find("Thermal", "Standby loss", 2), keepwarm_usd_yr=find("Thermal", "Keep-warm cost per year", 2),
                    whkg_levers=[wb["Mass_Levers"][f"{c}13"].value for c in "BCDE"])
    sheets = len(glob.glob(str(tmp / "c" / "*.csv")))
    shutil.rmtree(tmp, ignore_errors=True)
    return dict(verified=not errs and sheets >= 8, sheets_exported=sheets, errors=errs[:20], recalculated=vals,
                engine=subprocess.run([soffice, "--version"], capture_output=True, text=True).stdout.strip())


if __name__ == "__main__":
    build(); chk = verify()
    (OUT / "salt_model_check.json").write_text(json.dumps(chk, indent=1, default=str))
    print(json.dumps(chk, indent=1, default=str))
    sys.exit(0 if chk.get("verified") else 1)
