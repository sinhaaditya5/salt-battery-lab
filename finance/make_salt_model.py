#!/usr/bin/env python3
"""SaltIron_Engineering_Model.xlsx - live-formula workbook for the salt-iron designs (D3-D5), DFT and factory results.

Sheets: README, Inputs (blue = editable), Cell_BOM (P1 materials), Module_BOM (SM-48T), Thermal (keep-warm), Mass_Levers,
DFT_Results (S11), Factory (S15). Every derived cell is a formula that points at Inputs or at another sheet, so changing a
price or a dimension recalculates the whole workbook. Masses come from the CAD part lists (cad/out/smodule/*.csv).

Verification: LibreOffice (headless) recalculates the file, exports every sheet to CSV, and the script fails if any cell
shows an Excel/LibreOffice error (#VALUE!, #REF!, #DIV/0!, #NAME?, Err:). Key recalculated values -> salt_model_check.json.
Prices: mode of the S12 triangular ranges (sim/s12_chemistry_matrix/prices.py) or new [ASSUMPTION] rows - none is a quote.
Usage: python finance/make_salt_model.py  ->  PROJECT_SALT/10_ECONOMICS/SaltIron_Engineering_Model.xlsx (+ check json)
"""
