#!/usr/bin/env python3
"""Analyze galvanostatic cycler data in the R0 canonical CSV format.

Required columns: time_s, cycle, step, voltage_V, current_A
step must identify charge/discharge (e.g. 'charge', 'discharge').
Current is integrated as an absolute value; voltage must be cell terminal voltage.
The tool reports capacity/energy on both total-active-mass and mean-single-
electrode-mass bases because the 2019 paper's full-cell normalization needs
explicit confirmation before a like-for-like comparison.

No data are generated by this script. It rejects malformed input and writes
per-cycle and aggregate summaries from measured CSV files only.
"""
from __future__ import annotations
import argparse, csv, json, math
from collections import defaultdict
from pathlib import Path

REQUIRED = {"time_s", "cycle", "step", "voltage_V", "current_A"}


def read_rows(path: Path):
    groups = defaultdict(list)
    source_statuses = set()
    with path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        missing = REQUIRED - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"Missing required columns: {', '.join(sorted(missing))}")
        for line_no, row in enumerate(reader, start=2):
            try:
                t = float(row["time_s"])
                cyc = int(row["cycle"])
                step = row["step"].strip().lower()
                v = float(row["voltage_V"])
                i = float(row["current_A"])
            except (TypeError, ValueError) as e:
                raise ValueError(f"Invalid numeric value at CSV line {line_no}: {e}") from e
            if not all(math.isfinite(x) for x in (t, v, i)):
                raise ValueError(f"Non-finite numeric value at CSV line {line_no}")
            if step not in {"charge", "discharge"}:
                raise ValueError(f"step must be 'charge' or 'discharge' at line {line_no}; got {step!r}")
            if row.get("data_status", "").strip():
                source_statuses.add(row["data_status"].strip())
            groups[(cyc, step)].append((t, v, i))
    if not groups:
        raise ValueError("No data rows found")
    return groups, sorted(source_statuses)


def integrate(points):
    points = sorted(points, key=lambda x: x[0])
    cap_as = energy_j = duration_s = 0.0
    for a, b in zip(points, points[1:]):
        dt = b[0] - a[0]
        if dt < 0:
            raise ValueError("Time must be monotonic within each cycle/step")
        if dt == 0:
            continue
        # Trapezoidal integration using absolute current and absolute electrical power.
        cap_as += (abs(a[2]) + abs(b[2])) * 0.5 * dt
        pa, pb = abs(a[1] * a[2]), abs(b[1] * b[2])
        energy_j += (pa + pb) * 0.5 * dt
        duration_s += dt
    return {"capacity_mAh": cap_as / 3.6,
            "energy_mWh": energy_j / 3.6,
            "duration_s": duration_s,
            "mean_voltage_V": (sum(p[1] for p in points) / len(points)) if points else 0.0}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("input_csv", type=Path)
    p.add_argument("--positive-active-mg", type=float, required=True,
                   help="Measured active mass on positive-side electrode, mg")
    p.add_argument("--negative-active-mg", type=float, required=True,
                   help="Measured active mass on negative-side electrode, mg")
    p.add_argument("--out-dir", type=Path, default=Path("analysis_out"))
    args = p.parse_args()
    if args.positive_active_mg <= 0 or args.negative_active_mg <= 0:
        p.error("Active masses must be positive measured values.")
    total_g = (args.positive_active_mg + args.negative_active_mg) / 1000.0
    mean_electrode_g = ((args.positive_active_mg + args.negative_active_mg) / 2.0) / 1000.0

    grouped, source_statuses = read_rows(args.input_csv)
    by_cycle = defaultdict(dict)
    for (cycle, step), points in grouped.items():
        by_cycle[cycle][step] = integrate(points)

    out_rows = []
    for cycle in sorted(by_cycle):
        x = by_cycle[cycle]
        ch, dis = x.get("charge"), x.get("discharge")
        if not ch or not dis:
            continue
        ce = (dis["capacity_mAh"] / ch["capacity_mAh"]) if ch["capacity_mAh"] else None
        ee = (dis["energy_mWh"] / ch["energy_mWh"]) if ch["energy_mWh"] else None
        out_rows.append({
            "cycle": cycle,
            "source_data_status": ";".join(source_statuses) if source_statuses else "NOT_SPECIFIED_BY_INPUT",
            "charge_capacity_mAh": ch["capacity_mAh"],
            "discharge_capacity_mAh": dis["capacity_mAh"],
            "charge_energy_mWh": ch["energy_mWh"],
            "discharge_energy_mWh": dis["energy_mWh"],
            "charge_duration_s": ch["duration_s"],
            "discharge_duration_s": dis["duration_s"],
            "coulombic_efficiency_fraction": ce,
            "energy_efficiency_fraction": ee,
            "discharge_mAh_g_total_active_mass": dis["capacity_mAh"] / total_g,
            "discharge_mAh_g_mean_single_electrode_mass": dis["capacity_mAh"] / mean_electrode_g,
            "discharge_Wh_kg_total_active_mass": dis["energy_mWh"] / total_g,
            "discharge_Wh_kg_mean_single_electrode_mass": dis["energy_mWh"] / mean_electrode_g,
        })

    if not out_rows:
        raise ValueError("No complete cycles with both charge and discharge steps found")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_csv = args.out_dir / "cycle_summary.csv"
    with out_csv.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(out_rows[0]))
        writer.writeheader(); writer.writerows(out_rows)

    last = out_rows[-1]
    summary = {
        "input_file": str(args.input_csv.resolve()),
        "cycles_analyzed": len(out_rows),
        "positive_active_mass_mg": args.positive_active_mg,
        "negative_active_mass_mg": args.negative_active_mg,
        "total_active_mass_mg": args.positive_active_mg + args.negative_active_mg,
        "normalization_note": "Both total-active-mass and mean-single-electrode-mass bases are reported. State the selected denominator in every comparison.",
        "last_cycle": last,
        "data_status": ("SYNTHETIC_TEST_ONLY" if any("SYNTHETIC" in status.upper() for status in source_statuses) else "ANALYZED_FROM_INPUT_FILE; not independently verified"),
        "source_data_status_values": source_statuses,
    }
    (args.out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"Analyzed {len(out_rows)} complete cycles")
    print(f"Wrote {out_csv}")
    print(f"Wrote {args.out_dir / 'summary.json'}")
    print("No performance claim is valid until masses, sign conventions, instrument export and test conditions are verified.")

if __name__ == "__main__":
    main()
