#!/usr/bin/env python3
"""Generate MATLAB stem-diagram scripts (matlab/stem/*.m) from the lab's result JSONs, then (optionally) run them.

Each .m file is self-contained: the data are embedded as literal arrays, with the JSON source named in the header, so
the figure can be re-made in MATLAB (R2019b+) or GNU Octave (8+) without this repository. Only functions common to both
are used (figure, stem, hold, set, xlabel, ylabel, title, legend, grid, print).

Usage:  python tools/matlab/make_stem.py            # write scripts
        python tools/matlab/make_stem.py --run      # write + run with octave-cli under xvfb-run (EC2 build host)
Output: matlab/stem/stem_NN_<name>.m, matlab/stem/run_all_stem.m, matlab/stem/out/stem_NN_<name>.png, stem_manifest.json
Labels: the plotted values carry the labels of their sources ([SIMULATED] DFT/S14, [CALCULATED] S12/S15/S16).
"""
from __future__ import annotations
import json, shutil, subprocess, sys
from pathlib import Path

LAB = Path(__file__).resolve().parents[2]; D = LAB / "matlab" / "stem"; (D / "out").mkdir(parents=True, exist_ok=True)
J = lambda p: json.load(open(LAB / p))
C = ["[0.165 0.471 0.839]", "[0.922 0.408 0.204]", "[0.106 0.686 0.478]", "[0.929 0.631 0.000]", "[0.384 0.314 0.839]"]


def arr(v):
    return "[" + " ".join(f"{x:.6g}" if x is not None else "NaN" for x in v) + "]"


def cells(v):
    return "{" + ", ".join("'" + s.replace("'", "''") + "'" for s in v) + "}"


def header(name, title, src, label):
    return (f"%% {name}.m - {title}\n% Generated by tools/matlab/make_stem.py from {src}. Values: {label}.\n"
            f"% Runs in MATLAB R2019b+ and GNU Octave 8+. Output: out/{name}.png\n"
            "if exist('OCTAVE_VERSION', 'builtin'), graphics_toolkit('gnuplot'); end   % Octave only; MATLAB skips this line\n"
            "fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 960 520]);\n"
            "set(fig, 'PaperPositionMode', 'auto');\nhold on; grid on; box off;\n"
            "try, set(gca, 'GridColor', [0.80 0.80 0.80], 'GridAlpha', 0.6); catch, end\n")


def footer(name):
    return (f"set(gca, 'FontSize', 11, 'LineWidth', 0.8);\n"
            f"if ~exist('out', 'dir'), mkdir('out'); end\nprint(fig, fullfile('out', '{name}.png'), '-dpng', '-r200');\nclose(fig);\n")


def xt(labels):
    return (f"set(gca, 'XTick', 1:{len(labels)}, 'XTickLabel', {cells(labels)});\n"
            "try, set(gca, 'XTickLabelRotation', 35); catch, end\n")


def scripts():
    S = {}
    s11 = J("sim/s11_dft_chlorides/out/s11_results.json")
    # 1 voltages DFT vs experiment
    keys = ["Na+1/2Cl2", "FeCl2_U0", "CoCl2_U0", "NiCl2_U0"]; v = s11["voltages"]
    lab = ["Na + 1/2 Cl_2", "FeCl_2 (U=0)", "CoCl_2 (U=0)", "NiCl_2 (U=0)"]
    n = "stem_01_dft_vs_expt_voltage"
    S[n] = header(n, "DFT vs experimental conversion voltages", "sim/s11_dft_chlorides/out/s11_results.json", "[SIMULATED] vs [PUBLISHED]") + \
        f"x = 1:{len(keys)};\ndft = {arr([v[k]['dft_V'] for k in keys])};\nexpH = {arr([v[k]['exp_dH_V'] for k in keys])};\n" \
        f"h1 = stem(x - 0.12, dft, 'filled', 'LineWidth', 2, 'Color', {C[0]}, 'MarkerFaceColor', {C[0]}, 'MarkerSize', 8);\n" \
        f"h2 = stem(x + 0.12, expH, 'LineWidth', 2, 'Color', {C[1]}, 'MarkerSize', 8);\n" + xt(lab) + \
        "xlim([0.4 4.6]); ylim([0 4.6]); ylabel('Voltage vs Na (V)');\n" \
        "title('Na-metal-chloride couples: PBE (U = 0) vs experiment (\\DeltaH, 298 K)');\nlegend([h1 h2], {'DFT (PBE-D3)', 'Experiment (\\DeltaH)'}, 'Location', 'northeast');\n" + footer(n)
    # 2 voltage vs U
    n = "stem_02_voltage_vs_U"; body = ""
    for i, m in enumerate(("Fe", "Co", "Ni")):
        row = s11["uscan"][f"{m}Cl2_geomU4"]; U = sorted(int(u) for u in row)
        body += f"U = {arr(U)}; V = {arr([row[str(u)]['V'] for u in U])};\nh{i} = stem(U + {(-0.3 + 0.3 * i):.2f}, V, 'filled', 'LineWidth', 1.8, 'Color', {C[i]}, 'MarkerFaceColor', {C[i]});\n"
        body += f"plot([-0.6 6.6], [{s11['voltages'][f'{m}Cl2_U0']['exp_dH_V']:.4f} {s11['voltages'][f'{m}Cl2_U0']['exp_dH_V']:.4f}], '--', 'Color', {C[i]});\n"
    S[n] = header(n, "Conversion voltage vs Hubbard U", "s11_results.json -> uscan (U = 4 eV geometry)", "[SIMULATED]") + body + \
        "xlim([-0.8 6.8]); ylim([2.2 3.9]); xlabel('Hubbard U on M-3d (eV); metal reference at U = 0'); ylabel('Voltage vs Na (V)');\n" \
        "title('Voltage rises 0.1-0.2 V per eV of U (dashed: experiment)');\nlegend([h0 h1 h2], {'FeCl_2', 'CoCl_2', 'NiCl_2'}, 'Location', 'northwest');\n" + footer(n)
    # 3 band gap vs U
    n = "stem_03_gap_vs_U"; body = ""
    for i, m in enumerate(("Fe", "Co", "Ni")):
        row = s11["uscan"][f"{m}Cl2_geomU4"]; U = sorted(int(u) for u in row)
        body += f"U = {arr(U)}; G = {arr([row[str(u)]['gap_eV'] for u in U])};\nh{i} = stem(U + {(-0.3 + 0.3 * i):.2f}, G, 'filled', 'LineWidth', 1.8, 'Color', {C[i]}, 'MarkerFaceColor', {C[i]});\n"
    S[n] = header(n, "Band gap vs Hubbard U", "s11_results.json -> uscan", "[SIMULATED]") + body + \
        "xlim([-0.8 6.8]); xlabel('Hubbard U (eV)'); ylabel('Gap on SCF k-mesh (eV)');\n" \
        "title('FeCl_2 stays metallic in the symmetric cell; CoCl_2 and NiCl_2 open with U');\nlegend([h0 h1 h2], {'FeCl_2', 'CoCl_2', 'NiCl_2'}, 'Location', 'northwest');\n" + footer(n)
    # 4 magnetic order
    mg = s11["magnetic"]; ks = [k for k in ("FeCl2_U0", "FeCl2_U4", "CoCl2_U0", "CoCl2_U4", "NiCl2_U0", "NiCl2_U4") if k in mg]
    n = "stem_04_magnetic_order"
    S[n] = header(n, "Interlayer AFM vs FM energy", "s11_results.json -> magnetic", "[SIMULATED]") + \
        f"dE = {arr([mg[k]['E_AFM_minus_FM_meV_per_fu'] for k in ks])};\nstem(1:{len(ks)}, dE, 'filled', 'LineWidth', 2, 'Color', {C[4]}, 'MarkerFaceColor', {C[4]}, 'MarkerSize', 8);\n" + \
        xt([k.replace("Cl2_U", "Cl_2, U=") for k in ks]) + "plot([0.4 6.6], [0 0], 'k-');\nylabel('E_{AFM} - E_{FM} (meV per formula unit)');\n" \
        "title('Interlayer antiferromagnetic order is lower in every case (few meV)');\n" + footer(n)
    # 5 convergence
    cv = s11["convergence"]["NiCl2_FM"]; ec = sorted((int(k[4:]), val) for k, val in cv.items() if k.startswith("ecut"))
    n = "stem_05_cutoff_convergence"
    S[n] = header(n, "NiCl2 plane-wave cutoff convergence", "s11_results.json -> convergence", "[SIMULATED]") + \
        f"ec = {arr([e for e, _ in ec])}; dE = abs({arr([x for _, x in ec])}) + 1e-3;\nstem(ec, dE, 'filled', 'LineWidth', 2, 'Color', {C[0]}, 'MarkerFaceColor', {C[0]}, 'MarkerSize', 8);\n" \
        "set(gca, 'YScale', 'log'); plot([28 72], [2 2], '--', 'Color', [0.5 0.5 0.5]);\nxlabel('Wavefunction cutoff (Ry), \\rho cutoff = 8x'); ylabel('|E - E_{70 Ry}| (meV/atom)');\n" \
        "title('Production cutoff 50 Ry is within ~2.5 meV/atom of 70 Ry');\n" + footer(n)
    # 6 S12 practical vs theoretical
    r = J("sim/s12_chemistry_matrix/out/s12_results.json")["results"]; rows = sorted(r.values(), key=lambda x: -x["cell_P50"])
    n = "stem_06_chemistry_matrix_whkg"
    S[n] = header(n, "30 architectures: cell-level specific energy", "sim/s12_chemistry_matrix/out/s12_results.json", "[CALCULATED] P50 / [THEORETICAL]") + \
        f"p50 = {arr([x['cell_P50'] for x in rows])};\nth = {arr([x['theoretical_Whkg'] for x in rows])};\nx = 1:{len(rows)};\n" \
        f"h1 = stem(x, th, 'LineWidth', 1.2, 'Color', [0.7 0.7 0.7], 'MarkerSize', 5);\nh2 = stem(x, p50, 'filled', 'LineWidth', 1.8, 'Color', {C[1]}, 'MarkerFaceColor', {C[1]}, 'MarkerSize', 6);\n" + \
        xt([x["id"] for x in rows]) + "set(gca, 'YScale', 'log'); plot([0 31], [360 360], 'k--');\nylabel('Wh/kg'); xlim([0 31]);\n" \
        "title('No salt-derived architecture reaches 360 Wh/kg at cell level (dashed)');\nlegend([h1 h2], {'theoretical (active pair)', 'cell P50 (calibrated build-up)'}, 'Location', 'northeast');\n" + footer(n)
    # 7 S14 utilisation vs loading
    s14 = J("sim/s14_scell_model/out/s14_results.json")["runs"]; body = ""
    for i, j in enumerate((5.0, 10.0, 20.0, 33.3)):
        pts = sorted((x["qa"], x["utilisation"]) for x in s14 if x["mode"] == "dis" and abs(x["j"] - j) < 1e-6)
        body += f"q = {arr([p for p, _ in pts])}; u = 100 * {arr([u for _, u in pts])};\nh{i} = stem(q + {(-4.5 + 3 * i):.1f}, u, 'filled', 'LineWidth', 1.8, 'Color', {C[i]}, 'MarkerFaceColor', {C[i]});\n"
    n = "stem_07_scell_utilisation"
    S[n] = header(n, "Salt-iron cell: utilisation vs areal capacity", "sim/s14_scell_model/out/s14_results.json", "[SIMULATED] 0-D model") + body + \
        "plot([20 110], [80 80], 'k--'); xlim([20 110]); ylim([0 105]);\nxlabel('Areal capacity (mAh/cm^2)'); ylabel('Utilisation to 1.8 V (%)');\n" \
        "title('G2 needs >= 80 % (dashed); this 0-D model gives 100 % everywhere - it cannot test G2');\nlegend([h0 h1 h2 h3], {'5 mA/cm^2', '10 mA/cm^2', '20 mA/cm^2', '33.3 mA/cm^2'}, 'Location', 'southwest');\n" + footer(n)
    # 8 S15 factory cost vs scale
    sc = J("sim/s15_factory/out/s15_results.json")["scenarios"]; body = ""; hs = []; labs = []
    for i, (line, reg) in enumerate((("S03", "India"), ("S03", "USA"), ("N02", "India"), ("N02", "USA"))):
        pts = sorted((s["MWh_per_yr"], s["cell_cost_usd_kWh"]) for s in sc if s["line"] == line and s["region"] == reg)
        body += f"m = {arr([p for p, _ in pts])}; c = {arr([c for _, c in pts])};\nh{i} = stem(m * {(0.82 + 0.12 * i):.2f}, c, 'filled', 'LineWidth', 1.8, 'Color', {C[i]}, 'MarkerFaceColor', {C[i]});\n"
        labs.append(f"{'salt-iron S03' if line == 'S03' else 'NFPP Na-ion N02'}, {reg}")
    n = "stem_08_factory_cost_scale"
    S[n] = header(n, "Cell cost vs factory scale", "sim/s15_factory/out/s15_results.json", "[CALCULATED]") + body + \
        "set(gca, 'XScale', 'log', 'YScale', 'log'); plot([0.5 2000], [3 3], 'k--');\nxlabel('Factory output (MWh/yr)'); ylabel('Cell cost (USD/kWh)');\n" \
        f"title('USD 3/kWh (dashed) is 25-900x below every scenario');\nlegend([h0 h1 h2 h3], {cells(labs)}, 'Location', 'southwest');\n" + footer(n)
    # 9 S16 standby loss vs insulation
    s16p = LAB / "sim/s16_module_thermal/out/s16_results.json"
    if s16p.exists():
        s16 = json.load(open(s16p)); t = s16["standby_sweep"]["t_mm"]; W = s16["standby_sweep"]["W"]; body = ""
        for i, k in enumerate(("evacuated panel, 25 C", "microporous board, 25 C")):
            body += f"t = {arr(t)}; w = {arr(W[k])};\nh{i} = stem(t + {(-0.8 + 1.6 * i):.1f}, w, 'filled', 'LineWidth', 1.5, 'Color', {C[i]}, 'MarkerFaceColor', {C[i]}, 'MarkerSize', 5);\n"
        n = "stem_09_module_standby_loss"
        S[n] = header(n, "SM-48T keep-warm power vs insulation", "sim/s16_module_thermal/out/s16_results.json", "[CALCULATED]") + body + \
            "set(gca, 'YScale', 'log'); xlabel('Insulation thickness (mm)'); ylabel('Standby loss at 190 C, 25 C ambient (W)');\n" \
            "title('Evacuated panel: ~5x lower keep-warm power than microporous board');\nlegend([h0 h1], {'evacuated double wall', 'microporous board'}, 'Location', 'northeast');\n" + footer(n)
    return S


def main(argv):
    S = scripts()
    for k in S:      # thicker stems: gnuplot renders MATLAB line widths thin
        for a_, b_ in (("'LineWidth', 2,", "'LineWidth', 3,"), ("'LineWidth', 1.8,", "'LineWidth', 2.8,"), ("'LineWidth', 1.5,", "'LineWidth', 2.4,"), ("'LineWidth', 1.2,", "'LineWidth', 2,")):
            S[k] = S[k].replace(a_, b_)
    for n, body in S.items():
        (D / f"{n}.m").write_text(body)
    (D / "run_all_stem.m").write_text("% Run every stem script in this folder (MATLAB or Octave).\nfiles = dir('stem_*.m');\n"
                                      "for k = 1:numel(files)\n  [~, nm] = fileparts(files(k).name);\n  fprintf('%s\\n', nm);\n  run(files(k).name);\nend\n")
    man = dict(scripts=sorted(S), engine=None, pngs=[])
    if "--run" in argv:
        oct = shutil.which("octave-cli") or shutil.which("octave")
        if not oct:
            print("octave not installed - scripts written only"); man["engine"] = "not run"
        else:
            cmd = [oct, "--no-gui", "--quiet", "--eval", "run_all_stem"]       # no display -> gnuplot backend (headless print)
            import os, tempfile
            env = dict(os.environ, TMPDIR=tempfile.gettempdir() if " " not in tempfile.gettempdir() else "/tmp")   # ghostscript breaks on spaces
            if " " in env["TMPDIR"]: env["TMPDIR"] = "/tmp"
            env.pop("DISPLAY", None)
            r = subprocess.run(cmd, cwd=D.resolve(), capture_output=True, text=True, env=env)
            ver = subprocess.run([oct, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
            man["engine"] = ver; man["returncode"] = r.returncode; man["stderr_tail"] = r.stderr[-800:]
            man["pngs"] = sorted(p.name for p in (D / "out").glob("stem_*.png"))
            print(r.stdout[-1500:], r.stderr[-1500:])
    (D / "stem_manifest.json").write_text(json.dumps(man, indent=1))
    print(json.dumps(man, indent=1))


if __name__ == "__main__":
    main(sys.argv[1:])
